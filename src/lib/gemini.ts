export interface CanvasSolutionStep {
  stepNumber: number;
  title: string;
  explanation: string;
  math: string;
}

export interface CanvasSolution {
  problemSummary: string;
  subject: string;
  topic: string;
  keyFormulae: string[];
  steps: CanvasSolutionStep[];
  finalAnswer: string;
  boardExamTips: string;
  practiceQuestion: {
    question: string;
    hint: string;
  };
}

export interface SolveCanvasRequest {
  imageBase64?: string;
  prompt?: string;
  subject?: string;
}

const PRIMARY_MODEL = "gemini-flash-lite-latest";

export async function solveProblemWithGemini(
  request: SolveCanvasRequest
): Promise<CanvasSolution> {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) {
    throw new Error("GEMINI_API_KEY is not configured in environment.");
  }

  const systemInstruction = `You are the Senior Faculty & AI Academic Mentor at ALIVE Institute Indore, India's premier coaching center for Class 6-12 (CBSE, ICSE, MP Board, IIT-JEE Foundation & NEET).
Your role is to guide students with crystalline pedagogical clarity, rigorous step-by-step mathematical proofs/derivations, and actionable exam strategies.

When analyzing the student's handwritten math/science problem or drawing:
1. Accurately decipher handwritten mathematical equations, geometry sketches, physics circuit/ray diagrams, or chemical reactions.
2. Structure the solution with standard CBSE/ICSE board marking scheme steps.
3. Use clean LaTeX formatting for all mathematical symbols (e.g. \\frac{-b \\pm \\sqrt{b^2 - 4ac}}{2a}, \\int_0^1 x^2 dx, \\vec{F} = m\\vec{a}).
4. Identify high-frequency board exam mistakes and traps students should avoid.
5. Provide a closely related practice problem.

YOU MUST RESPOND IN VALID JSON FORMAT ONLY (no markdown code blocks, or clean JSON within markdown) matching this TypeScript schema:
{
  "problemSummary": "string describing the deciphered question/equation",
  "subject": "Mathematics | Physics | Chemistry | Biology | General",
  "topic": "Specific chapter/topic name (e.g. Quadratic Equations, Ray Optics, Chemical Kinetics)",
  "keyFormulae": ["array of LaTeX formulas used"],
  "steps": [
    {
      "stepNumber": 1,
      "title": "Step title (e.g. Identify coefficients and compute discriminant)",
      "explanation": "Clear conceptual explanation in plain English",
      "math": "Key LaTeX formula or step expression"
    }
  ],
  "finalAnswer": "Explicit final value/answer in LaTeX",
  "boardExamTips": "Vital tips for full marks in board exams, common sign errors or unit omissions to watch out for",
  "practiceQuestion": {
    "question": "A similar question for the student to try next",
    "hint": "Brief hint to guide them"
  }
}`;

  const parts: Array<any> = [
    {
      text: `${systemInstruction}\n\nStudent prompt / notes: ${
        request.prompt || "Please solve and explain the drawing on this whiteboard."
      }\nTarget Subject context: ${request.subject || "Auto-detect"}\n\nProvide the JSON response now:`,
    },
  ];

  // If canvas drawing is attached
  if (request.imageBase64) {
    let cleanBase64 = request.imageBase64;
    let mimeType = "image/png";

    if (cleanBase64.includes(";base64,")) {
      const split = cleanBase64.split(";base64,");
      const mimeMatch = split[0].match(/:(.*?)$/);
      if (mimeMatch) mimeType = mimeMatch[1];
      cleanBase64 = split[1];
    }

    parts.push({
      inlineData: {
        mimeType: mimeType,
        data: cleanBase64,
      },
    });
  }

  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${PRIMARY_MODEL}:generateContent?key=${apiKey}`;

  const response = await fetch(endpoint, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      contents: [{ parts }],
      generationConfig: {
        temperature: 0.2,
        maxOutputTokens: 2048,
        responseMimeType: "application/json",
      },
    }),
  });

  if (!response.ok) {
    const errorText = await response.text();
    console.error("Gemini API error:", response.status, errorText);
    throw new Error(`Gemini API error (${response.status}): ${errorText.slice(0, 150)}`);
  }

  const data = await response.json();
  const rawText = data.candidates?.[0]?.content?.parts?.[0]?.text;

  if (!rawText) {
    throw new Error("No response content generated by Gemini.");
  }

  try {
    // Strip possible markdown fences if returned
    const cleaned = rawText
      .replace(/^```json\s*/i, "")
      .replace(/^```\s*/i, "")
      .replace(/\s*```$/i, "")
      .trim();
    return JSON.parse(cleaned) as CanvasSolution;
  } catch (parseError) {
    console.warn("Failed to parse JSON directly, falling back to structured representation:", parseError);
    return {
      problemSummary: request.prompt || "Recognized problem on whiteboard",
      subject: request.subject || "Mathematics",
      topic: "Conceptual Derivation",
      keyFormulae: [],
      steps: [
        {
          stepNumber: 1,
          title: "Solution & Derivation",
          explanation: rawText,
          math: "",
        },
      ],
      finalAnswer: "See derivation above",
      boardExamTips: "Ensure step-by-step working is clearly shown in your board answer sheet.",
      practiceQuestion: {
        question: "Try solving with different initial values.",
        hint: "Follow the same conceptual framework.",
      },
    };
  }
}
